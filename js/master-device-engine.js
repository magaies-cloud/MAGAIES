        root.style.setProperty('--vh', `${vh}px`);
        root.style.setProperty('--app-height', `${window.innerHeight}px`);
        root.style.setProperty('--safe-top', device.safeTop);
        root.style.setProperty('--safe-bottom', device.safeBottom);
        root.style.setProperty('--curve-guard-left', device.curveGuardLeft);
        root.style.setProperty('--curve-guard-right', device.curveGuardRight);
        root.style.setProperty('--device-accent', device.color);

        // 2. حساب مقياس الواجهة الذكي (UI Scale) وعرض البطاقة المتكيف
